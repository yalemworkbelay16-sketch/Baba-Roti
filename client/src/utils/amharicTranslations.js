/**
 * Translate a category name to Amharic if current language is 'am'.
 */
export function getLocalizedCategory(category, lang) {
  if (lang !== 'am' || !category) return category || 'All Items';
  const clean = category.trim().toLowerCase();
  return CATEGORY_AMHARIC_MAP[clean] || category;
}

/**
 * Translate product name to Amharic if current language is 'am'.
 */
export function getLocalizedProductName(product, lang) {
  if (!product) return '';
  if (lang !== 'am') return product.name || '';
  if (product.nameAmharic && product.nameAmharic.trim()) {
    return product.nameAmharic.trim();
  }

  const rawName = (product.name || '').trim();
  if (COMMON_FOOD_TERMS[rawName]) return COMMON_FOOD_TERMS[rawName];

  // Try case-insensitive exact check
  const exactKey = Object.keys(COMMON_FOOD_TERMS).find(k => k.toLowerCase() === rawName.toLowerCase());
  if (exactKey) return COMMON_FOOD_TERMS[exactKey];

  // Tokenize and replace known words
  const words = rawName.split(/[\s,()\-]+/i).filter(Boolean);
  let changed = false;
  const translatedWords = words.map(w => {
    const lower = w.toLowerCase();
    if (WORD_MAP[lower]) {
      changed = true;
      return WORD_MAP[lower];
    }
    return w;
  });

  return changed ? translatedWords.join(' ') : rawName;
}
